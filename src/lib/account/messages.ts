export const ACCOUNT_MESSAGES: Record<Locale, Record<AccountMessageKey, string>> = { en, fa };

export function accountText(locale: Locale, key: AccountMessageKey, vars?: Record<string, string | number>): string {
  let s = ACCOUNT_MESSAGES[locale][key] ?? ACCOUNT_MESSAGES.en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function useAccountText() {
  const { locale } = useI18n();
  return useCallback((key: AccountMessageKey, vars?: Record<string, string | number>) => accountText(locale, key, vars), [locale]);
}

export function errorMessageKey(kind: AccountErrorKind): AccountMessageKey {
  return `err_${kind}` as AccountMessageKey;
}
